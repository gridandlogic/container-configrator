export const ARCHITECTURAL_PRESETS = PRESET_MODELS;

export function getPresetsBySize(sizeCategory: '20ft' | '30ft' | '40ft' | 'double-wide' | 'multi-story'): ContainerModelConfig[] {
  switch (sizeCategory) {
    case '20ft':
      return PRESET_MODELS.filter((p) => p.lengthFt === 20 && p.layoutType === 'single');
    case '30ft':
      return PRESET_MODELS.filter((p) => p.lengthFt === 30 && p.layoutType === 'single');
    case '40ft':
      return PRESET_MODELS.filter((p) => (p.lengthFt === 40 || p.lengthFt === 45) && p.layoutType === 'single');
    case 'double-wide':
      return PRESET_MODELS.filter((p) => p.layoutType === 'double-wide' || p.widthFt >= 14);
    case 'multi-story':
      return PRESET_MODELS.filter((p) => p.layoutType === 'stacked-2story' || p.layoutType === 'l-shape');
    default:
      return PRESET_MODELS;
  }
}
